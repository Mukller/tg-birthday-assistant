/** Render a template by index, substituting the contact name. */
export function renderCongrat(index: number, name: string): string {
  const tpl = CONGRATS_TEMPLATES[index] ?? CONGRATS_TEMPLATES[0];
  return tpl.replace(/\{name\}/g, (name && name.trim()) || 'друг');
}

export interface CongratPageItem {
  index: number; // absolute index into CONGRATS_TEMPLATES
  text: string; // rendered with the name
}

/** A page of suggestions (wraps around). Returns rendered items + page meta. */
export function congratPage(name: string, page: number, perPage = 5) {
  const total = CONGRATS_TEMPLATES.length;
  const totalPages = Math.max(1, Math.ceil(total / perPage));
  const p = ((page % totalPages) + totalPages) % totalPages; // normalize/wrap
  const start = p * perPage;
  const items: CongratPageItem[] = [];
  for (let i = start; i < Math.min(start + perPage, total); i++) {
    items.push({ index: i, text: renderCongrat(i, name) });
  }
  return { page: p, totalPages, total, items };
}
